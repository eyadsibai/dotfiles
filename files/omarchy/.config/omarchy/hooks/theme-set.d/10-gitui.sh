#!/bin/bash

# Guard: omarchy-hook runs this dir a second time without the color env exported
# by the parent theme-set hook; skip that env-less pass entirely.
[[ -n "$primary_background" ]] || exit 0

# gitui: theme.ron in the config dir. Keys not listed keep gitui's defaults
# (partial themes are supported since 0.23). Colors are hex strings.

if ! command -v gitui >/dev/null 2>&1; then
    skipped "gitui"
fi

output_file="$theme_dir/gitui.ron"
target="$HOME/.config/gitui/theme.ron"
marker="Generated by ~/.config/omarchy/hooks/theme-set.d/10-gitui.sh"

if [[ ! -f "$output_file" ]]; then
cat > "$output_file" << RON
// $marker — do not edit.
(
    selected_tab: Some("#${accent}"),
    command_fg: Some("#${primary_foreground}"),
    selection_bg: Some("#${selection_background}"),
    selection_fg: Some("#${selection_foreground}"),
    cmdbar_bg: Some("#${lighter_background}"),
    disabled_fg: Some("#${muted}"),
    diff_line_add: Some("#${normal_green}"),
    diff_line_delete: Some("#${normal_red}"),
    diff_file_added: Some("#${bright_green}"),
    diff_file_removed: Some("#${bright_red}"),
    diff_file_moved: Some("#${bright_magenta}"),
    diff_file_modified: Some("#${normal_yellow}"),
    commit_hash: Some("#${normal_magenta}"),
    commit_time: Some("#${normal_cyan}"),
    commit_author: Some("#${normal_green}"),
    danger_fg: Some("#${normal_red}"),
    push_gauge_bg: Some("#${normal_blue}"),
    push_gauge_fg: Some("#${primary_background}"),
    tag_fg: Some("#${normal_yellow}"),
    branch_fg: Some("#${bright_yellow}"),
    block_title_focused: Some("#${accent}"),
)
RON
fi

mkdir -p "$(dirname "$target")"
# Keep a hand-written theme.ron once, before the first generated one replaces it.
if [[ -f "$target" && ! -f "$target.backup" ]] && ! grep -q "$marker" "$target"; then
    cp "$target" "$target.backup"
fi
cp -f "$output_file" "$target"

require_restart "gitui"
success "gitui theme updated!"
exit 0
