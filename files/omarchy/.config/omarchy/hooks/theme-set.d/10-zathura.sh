#!/bin/bash

# Guard: omarchy-hook runs this dir a second time without the color env exported
# by the parent theme-set hook; skip that env-less pass entirely.
[[ -n "$primary_background" ]] || exit 0

# zathura: palette goes to ~/.config/zathura/omarchy-colors and zathurarc gets
# a single `include omarchy-colors` line, so user settings in zathurarc survive.
# Dark themes turn recolor on (pages render fg-on-bg, images kept); light themes
# leave documents as printed. Ctrl+r toggles recolor at runtime either way.

if ! command -v zathura >/dev/null 2>&1; then
    skipped "Zathura"
fi

output_file="$theme_dir/zathura-colors"
config_dir="$HOME/.config/zathura"
rc_file="$config_dir/zathurarc"

if [[ "$theme_mode" == "light" ]]; then
    recolor=false
else
    recolor=true
fi

if [[ ! -f "$output_file" ]]; then
cat > "$output_file" << ZRC
# Generated by ~/.config/omarchy/hooks/theme-set.d/10-zathura.sh — do not edit.
set default-bg              "#${primary_background}"
set default-fg              "#${primary_foreground}"
set render-loading-bg       "#${primary_background}"
set render-loading-fg       "#${primary_foreground}"
set statusbar-bg            "#${lighter_background}"
set statusbar-fg            "#${primary_foreground}"
set inputbar-bg             "#${primary_background}"
set inputbar-fg             "#${bright_white}"
set notification-bg         "#${lighter_background}"
set notification-fg         "#${primary_foreground}"
set notification-error-bg   "#${normal_red}"
set notification-error-fg   "#${primary_background}"
set notification-warning-bg "#${normal_yellow}"
set notification-warning-fg "#${primary_background}"
set completion-bg           "#${lighter_background}"
set completion-fg           "#${primary_foreground}"
set completion-group-bg     "#${primary_background}"
set completion-group-fg     "#${accent}"
set completion-highlight-bg "#${accent}"
set completion-highlight-fg "#${primary_background}"
set index-bg                "#${primary_background}"
set index-fg                "#${primary_foreground}"
set index-active-bg         "#${accent}"
set index-active-fg         "#${primary_background}"
set highlight-color         "rgba(${rgb_normal_yellow}, 0.45)"
set highlight-active-color  "rgba(${rgb_bright_yellow}, 0.6)"
set highlight-fg            "#${primary_background}"
set recolor                 ${recolor}
set recolor-lightcolor      "#${primary_background}"
set recolor-darkcolor       "#${primary_foreground}"
set recolor-keephue         true
set recolor-reverse-video   true
ZRC
fi

mkdir -p "$config_dir"
cp -f "$output_file" "$config_dir/omarchy-colors"

if [[ ! -f "$rc_file" ]]; then
    printf '# Colors follow the Omarchy theme; see omarchy-colors.\ninclude omarchy-colors\n' > "$rc_file"
elif ! grep -qE '^\s*include\s+omarchy-colors\s*$' "$rc_file"; then
    printf '\n# Colors follow the Omarchy theme; see omarchy-colors.\ninclude omarchy-colors\n' >> "$rc_file"
fi

require_restart "zathura"
success "Zathura theme updated!"
exit 0
