#!/bin/bash

# Guard: omarchy-hook runs this dir a second time without the color env exported
# by the parent theme-set hook; skip that env-less pass entirely.
[[ -n "$primary_background" ]] || exit 0

# File listings: eza gets a full theme.yml (~/.config/eza/theme.yml), and a
# matching truecolor LS_COLORS is set as a fish universal variable so fd, tree
# and coreutils ls agree with it. Both are regenerated from the palette on
# every theme switch. Bash users can `source` the generated ls_colors.sh.
#
# Role mapping: directories = accent, symlinks = cyan, executables = green,
# source code = blue, config/data = orange, docs/text = yellow, build files =
# bright yellow bold, archives = red, images = magenta, media = bright magenta /
# cyan, temp and metadata columns = muted, dates = dark foreground.
# eza classifies source/build/media itself but knows nothing about shell, html,
# json/toml/yaml, config or text files, so LS_COLORS carries those globs (they
# take precedence in eza and are the only theming ls/fd/tree get).

if ! command -v eza >/dev/null 2>&1; then
    skipped "eza"
fi

theme_out="$theme_dir/eza-theme.yml"
fish_out="$theme_dir/ls_colors.fish"
sh_out="$theme_dir/ls_colors.sh"
eza_dir="${EZA_CONFIG_DIR:-$HOME/.config/eza}"
marker="Generated by ~/.config/omarchy/hooks/theme-set.d/10-eza.sh"

# "38;2;r;g;b" / "48;2;r;g;b" from a bare hex color.
fg() { printf '38;2;%s' "$(hex2rgb "$1" | tr -d ' ' | tr ',' ';')"; }
bg() { printf '48;2;%s' "$(hex2rgb "$1" | tr -d ' ' | tr ',' ';')"; }

if [[ ! -f "$theme_out" ]]; then
cat > "$theme_out" << YAML
# $marker — do not edit.
colourful: true

filekinds:
  normal: {foreground: "#${primary_foreground}"}
  directory: {foreground: "#${accent}", is_bold: true}
  symlink: {foreground: "#${normal_cyan}"}
  pipe: {foreground: "#${normal_yellow}"}
  block_device: {foreground: "#${normal_yellow}", is_bold: true}
  char_device: {foreground: "#${normal_yellow}", is_bold: true}
  socket: {foreground: "#${normal_magenta}", is_bold: true}
  special: {foreground: "#${normal_magenta}"}
  executable: {foreground: "#${normal_green}", is_bold: true}
  mount_point: {foreground: "#${normal_blue}", is_bold: true, is_underline: true}

perms:
  user_read: {foreground: "#${normal_yellow}"}
  user_write: {foreground: "#${normal_red}"}
  user_execute_file: {foreground: "#${normal_green}", is_bold: true}
  user_execute_other: {foreground: "#${normal_green}"}
  group_read: {foreground: "#${bright_yellow}"}
  group_write: {foreground: "#${bright_red}"}
  group_execute: {foreground: "#${bright_green}"}
  other_read: {foreground: "#${bright_yellow}"}
  other_write: {foreground: "#${bright_red}"}
  other_execute: {foreground: "#${bright_green}"}
  special_user_file: {foreground: "#${normal_magenta}"}
  special_other: {foreground: "#${normal_magenta}"}
  attribute: {foreground: "#${muted}"}

size:
  major: {foreground: "#${normal_green}", is_bold: true}
  minor: {foreground: "#${normal_green}"}
  number_byte: {foreground: "#${light_foreground}"}
  number_kilo: {foreground: "#${normal_green}"}
  number_mega: {foreground: "#${normal_yellow}"}
  number_giga: {foreground: "#${orange}"}
  number_huge: {foreground: "#${normal_red}"}
  unit_byte: {foreground: "#${muted}"}
  unit_kilo: {foreground: "#${normal_green}"}
  unit_mega: {foreground: "#${normal_yellow}"}
  unit_giga: {foreground: "#${orange}"}
  unit_huge: {foreground: "#${normal_red}"}

users:
  user_you: {foreground: "#${accent}", is_bold: true}
  user_other: {foreground: "#${primary_foreground}"}
  user_root: {foreground: "#${normal_red}", is_bold: true}
  group_yours: {foreground: "#${accent}"}
  group_other: {foreground: "#${dark_foreground}"}
  group_root: {foreground: "#${normal_red}"}

links:
  normal: {foreground: "#${muted}"}
  multi_link_file: {foreground: "#${normal_yellow}", is_bold: true}

git:
  new: {foreground: "#${normal_green}"}
  modified: {foreground: "#${normal_yellow}"}
  deleted: {foreground: "#${normal_red}"}
  renamed: {foreground: "#${normal_cyan}"}
  typechange: {foreground: "#${normal_magenta}"}
  ignored: {foreground: "#${muted}"}
  conflicted: {foreground: "#${normal_red}", is_bold: true}

git_repo:
  branch_main: {foreground: "#${normal_green}", is_bold: true}
  branch_other: {foreground: "#${normal_yellow}", is_bold: true}
  git_clean: {foreground: "#${normal_green}"}
  git_dirty: {foreground: "#${normal_yellow}"}

file_type:
  image: {foreground: "#${normal_magenta}"}
  video: {foreground: "#${bright_magenta}"}
  music: {foreground: "#${normal_cyan}"}
  lossless: {foreground: "#${bright_cyan}"}
  crypto: {foreground: "#${normal_yellow}"}
  document: {foreground: "#${normal_yellow}"}
  compressed: {foreground: "#${normal_red}"}
  temp: {foreground: "#${muted}"}
  compiled: {foreground: "#${orange}"}
  build: {foreground: "#${bright_yellow}"}
  source: {foreground: "#${normal_blue}"}

punctuation: {foreground: "#${muted}"}
date: {foreground: "#${dark_foreground}"}
inode: {foreground: "#${muted}"}
blocks: {foreground: "#${muted}"}
header: {foreground: "#${bright_white}", is_underline: true}
octal: {foreground: "#${normal_yellow}"}
flags: {foreground: "#${muted}"}
symlink_path: {foreground: "#${normal_cyan}"}
control_char: {foreground: "#${normal_red}"}
broken_symlink: {foreground: "#${normal_red}", is_bold: true}
broken_path_overlay: {foreground: "#${normal_red}", is_underline: true}
YAML
fi

if [[ ! -f "$fish_out" ]]; then
    # Standard dircolors keys (coreutils ls, fd, tree; eza reads di ln ex fi pi so bd cd or)
    ls_colors="rs=0"
    ls_colors+=":di=1;$(fg "$accent")"
    ls_colors+=":ln=$(fg "$normal_cyan")"
    ls_colors+=":mh=0"
    ls_colors+=":pi=$(fg "$normal_yellow")"
    ls_colors+=":so=1;$(fg "$normal_magenta")"
    ls_colors+=":do=$(fg "$normal_magenta")"
    ls_colors+=":bd=1;$(fg "$normal_yellow")"
    ls_colors+=":cd=1;$(fg "$normal_yellow")"
    ls_colors+=":or=1;$(fg "$normal_red")"
    ls_colors+=":mi=$(fg "$normal_red")"
    ls_colors+=":su=$(fg "$primary_background");$(bg "$normal_red")"
    ls_colors+=":sg=$(fg "$primary_background");$(bg "$normal_yellow")"
    ls_colors+=":ca=0"
    ls_colors+=":tw=$(fg "$primary_background");$(bg "$normal_green")"
    ls_colors+=":ow=1;$(fg "$accent");$(bg "$lighter_background")"
    ls_colors+=":st=$(fg "$primary_foreground");$(bg "$normal_blue")"
    ls_colors+=":ex=1;$(fg "$normal_green")"
    add_group() {
        local style=$1; shift
        local ext
        for ext in "$@"; do ls_colors+=":*.${ext}=${style}"; done
    }
    add_names() {
        local style=$1; shift
        local name
        for name in "$@"; do ls_colors+=":*${name}=${style}"; done
    }
    # Later entries win in ls, eza and fd, so build-file names come after the
    # extension groups they would otherwise match (Cargo.toml vs *.toml).
    add_group "$(fg "$normal_red")"       tar tgz tbz2 gz bz2 xz zst zip 7z rar jar iso deb rpm dmg
    add_group "$(fg "$normal_magenta")"   jpg jpeg png gif webp avif heic bmp ico svg tif tiff psd xcf
    add_group "$(fg "$bright_magenta")"   mp4 mkv mov webm avi m4v mpg mpeg
    add_group "$(fg "$normal_cyan")"      mp3 ogg opus m4a aac wma
    add_group "$(fg "$bright_cyan")"      flac wav aiff alac ape
    add_group "$(fg "$normal_blue")"      py rs go c h cc cpp hpp cxx hh java kt kts swift rb lua ex exs erl hs zig nix \
                                          js jsx mjs cjs ts tsx vue svelte astro html htm css scss sass less sql \
                                          sh bash zsh fish ps1 pl pm php r jl scala clj dart cs fs ml tex ipynb awk
    add_group "$(fg "$orange")"           json jsonc json5 toml yml yaml ini conf cfg xml csv tsv env lock properties \
                                          plist ron kdl hcl tf tfvars desktop service
    add_group "$(fg "$normal_yellow")"    md markdown txt rst org adoc pdf doc docx xls xlsx ppt pptx odt ods odp epub rtf
    add_group "$(fg "$muted")"            bak tmp swp swo log orig part crdownload
    add_names "1;$(fg "$bright_yellow")"  Makefile makefile GNUmakefile Justfile justfile Dockerfile Containerfile \
                                          CMakeLists.txt PKGBUILD Cargo.toml package.json pyproject.toml go.mod flake.nix \
                                          meson.build build.gradle pom.xml Gemfile Rakefile Pipfile mix.exs Procfile \
                                          Vagrantfile Brewfile tsconfig.json

    printf "# %s — do not edit.\nset -Ux LS_COLORS '%s'\n" "$marker" "$ls_colors" > "$fish_out"
    printf "# %s — do not edit. Bash users: source this from ~/.bashrc.\nexport LS_COLORS='%s'\n" "$marker" "$ls_colors" > "$sh_out"
fi

mkdir -p "$eza_dir"
if [[ -f "$eza_dir/theme.yml" && ! -f "$eza_dir/theme.yml.backup" ]] && ! grep -q "$marker" "$eza_dir/theme.yml"; then
    cp "$eza_dir/theme.yml" "$eza_dir/theme.yml.backup"
fi
cp -f "$theme_out" "$eza_dir/theme.yml"

if command -v fish >/dev/null 2>&1; then
    fish -c "source $fish_out"
fi

success "eza theme + LS_COLORS updated!"
exit 0
