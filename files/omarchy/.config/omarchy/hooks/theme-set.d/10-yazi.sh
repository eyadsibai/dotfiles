#!/bin/bash

# Guard: omarchy-hook runs this dir a second time without the color env exported
# by the parent theme-set hook; skip that env-less pass entirely.
[[ -n "$primary_background" ]] || exit 0

# Yazi: ship the palette as a flavor (flavors/omarchy.yazi) and point
# theme.toml's [flavor] at it for both dark and light. Anything not set here
# falls through to yazi's preset, and [filetype] rules keep their ANSI names so
# they follow the terminal palette. Schema: yazi 26.x (sections [app], [mgr],
# [indicator], ...).

if ! command -v yazi >/dev/null 2>&1; then
    skipped "Yazi"
fi

output_file="$theme_dir/yazi-flavor.toml"
flavor_dir="$HOME/.config/yazi/flavors/omarchy.yazi"
theme_file="$HOME/.config/yazi/theme.toml"

if [[ ! -f "$output_file" ]]; then
cat > "$output_file" << TOML
# Generated by ~/.config/omarchy/hooks/theme-set.d/10-yazi.sh — do not edit.

[app]
overall = { fg = "#${primary_foreground}", bg = "#${primary_background}" }

[mgr]
cwd = { fg = "#${normal_cyan}", bold = true }
find_keyword  = { fg = "#${normal_yellow}", bold = true, italic = true, underline = true }
find_position = { fg = "#${normal_magenta}", bg = "reset", bold = true, italic = true }
symlink_target = { fg = "#${muted}", italic = true }
marker_copied   = { fg = "#${normal_green}", bg = "#${normal_green}" }
marker_cut      = { fg = "#${normal_red}", bg = "#${normal_red}" }
marker_marked   = { fg = "#${normal_cyan}", bg = "#${normal_cyan}" }
marker_selected = { fg = "#${accent}", bg = "#${accent}" }
count_copied   = { fg = "#${primary_background}", bg = "#${normal_green}" }
count_cut      = { fg = "#${primary_background}", bg = "#${normal_red}" }
count_selected = { fg = "#${primary_background}", bg = "#${accent}" }
border_style = { fg = "#${muted}" }

[indicator]
parent  = { fg = "#${primary_foreground}", bg = "#${lighter_background}" }
current = { fg = "#${primary_background}", bg = "#${accent}", bold = true }
preview = { underline = true }

[tabs]
active   = { fg = "#${primary_background}", bg = "#${accent}", bold = true }
inactive = { fg = "#${primary_foreground}", bg = "#${lighter_background}" }

[mode]
normal_main = { fg = "#${primary_background}", bg = "#${accent}", bold = true }
normal_alt  = { fg = "#${accent}", bg = "#${lighter_background}" }
select_main = { fg = "#${primary_background}", bg = "#${normal_green}", bold = true }
select_alt  = { fg = "#${normal_green}", bg = "#${lighter_background}" }
unset_main  = { fg = "#${primary_background}", bg = "#${normal_red}", bold = true }
unset_alt   = { fg = "#${normal_red}", bg = "#${lighter_background}" }

[status]
overall = { fg = "#${primary_foreground}", bg = "#${primary_background}" }
perm_sep   = { fg = "#${muted}" }
perm_type  = { fg = "#${normal_green}" }
perm_read  = { fg = "#${normal_yellow}" }
perm_write = { fg = "#${normal_red}" }
perm_exec  = { fg = "#${normal_cyan}" }
progress_label  = { fg = "#${primary_foreground}", bold = true }
progress_normal = { fg = "#${accent}", bg = "#${lighter_background}" }
progress_error  = { fg = "#${normal_red}", bg = "#${lighter_background}" }

[which]
border = { fg = "#${accent}" }
mask   = { bg = "#${primary_background}" }
cand   = { fg = "#${normal_cyan}" }
rest   = { fg = "#${muted}" }
desc   = { fg = "#${normal_magenta}" }
separator_style = { fg = "#${muted}" }

[confirm]
border  = { fg = "#${accent}" }
title   = { fg = "#${accent}", bold = true }
body    = { fg = "#${primary_foreground}" }
list    = { fg = "#${primary_foreground}" }
btn_yes = { fg = "#${primary_background}", bg = "#${accent}", bold = true }
btn_no  = { fg = "#${primary_foreground}" }

[spot]
border   = { fg = "#${accent}" }
title    = { fg = "#${accent}" }
tbl_col  = { fg = "#${accent}" }
tbl_cell = { fg = "#${normal_yellow}", reversed = true }

[notify]
title_info  = { fg = "#${normal_green}" }
title_warn  = { fg = "#${normal_yellow}" }
title_error = { fg = "#${normal_red}" }

[pick]
border   = { fg = "#${accent}" }
active   = { fg = "#${normal_magenta}", bold = true }
inactive = { fg = "#${primary_foreground}" }

[input]
border   = { fg = "#${accent}" }
title    = { fg = "#${accent}" }
value    = { fg = "#${primary_foreground}" }
selected = { fg = "#${selection_foreground}", bg = "#${selection_background}" }

[cmp]
border   = { fg = "#${accent}" }
active   = { fg = "#${primary_background}", bg = "#${accent}" }
inactive = { fg = "#${primary_foreground}" }

[tasks]
border  = { fg = "#${accent}" }
title   = { fg = "#${accent}" }
hovered = { fg = "#${normal_magenta}", bold = true }

[help]
border  = { fg = "#${accent}" }
chord   = { fg = "#${normal_cyan}" }
action  = { fg = "#${primary_foreground}" }
hovered = { fg = "#${primary_background}", bg = "#${accent}", bold = true }
TOML
fi

mkdir -p "$flavor_dir"
cp -f "$output_file" "$flavor_dir/flavor.toml"

if [[ ! -f "$theme_file" ]]; then
    printf '[flavor]\ndark  = "omarchy"\nlight = "omarchy"\n' > "$theme_file"
elif ! grep -q '"omarchy"' "$theme_file"; then
    if grep -q '^\[flavor\]' "$theme_file"; then
        warning "Yazi: $theme_file already has a [flavor] section; set dark/light = \"omarchy\" there."
    else
        printf '\n[flavor]\ndark  = "omarchy"\nlight = "omarchy"\n' >> "$theme_file"
    fi
fi

require_restart "yazi"
success "Yazi flavor updated!"
exit 0
